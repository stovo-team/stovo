-- Repair databases where the former runtime Ent migration created sequence as
-- a nullable bigint instead of the Atlas-owned identity column. Writers omit
-- sequence and must receive a non-null monotonically increasing value.
ALTER TABLE sync_events
    ALTER COLUMN sequence DROP IDENTITY IF EXISTS;

ALTER TABLE sync_events
    ALTER COLUMN sequence DROP DEFAULT;

ALTER TABLE sync_events
    ALTER COLUMN sequence ADD GENERATED BY DEFAULT AS IDENTITY;

UPDATE sync_events
SET sequence = DEFAULT
WHERE sequence IS NULL;

SELECT setval(
    pg_get_serial_sequence('sync_events', 'sequence'),
    COALESCE((SELECT MAX(sequence) FROM sync_events), 1),
    (SELECT COUNT(*) > 0 FROM sync_events)
);

ALTER TABLE sync_events
    ALTER COLUMN sequence SET NOT NULL;
